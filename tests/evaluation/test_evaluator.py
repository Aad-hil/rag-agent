from unittest.mock import patch

from app.evaluation.benchmark import (
    BenchmarkQuestionResult,
    BenchmarkSummary,
)
from app.evaluation.evaluator import (
    _format_pages,
    _print_question_result,
    _print_summary,
    evaluate,
)
from app.evaluation.generation import GenerationEvaluationResult


def make_generation_result(
    has_answer: bool = True,
    is_abstention: bool = False,
    has_citations: bool = True,
    citations_valid: bool = True,
    citation_pages: tuple[int, ...] = (20,),
    retrieved_pages: tuple[int, ...] = (20, 50),
    cited_relevant_pages: tuple[int, ...] = (20,),
    unsupported_citation_pages: tuple[int, ...] = (),
) -> GenerationEvaluationResult:
    return GenerationEvaluationResult(
        has_answer=has_answer,
        is_abstention=is_abstention,
        has_citations=has_citations,
        citations_valid=citations_valid,
        citation_pages=citation_pages,
        retrieved_pages=retrieved_pages,
        cited_relevant_pages=cited_relevant_pages,
        unsupported_citation_pages=unsupported_citation_pages,
    )


def make_question_result(
    generation: GenerationEvaluationResult | None = None,
    error: str | None = None,
) -> BenchmarkQuestionResult:
    return BenchmarkQuestionResult(
        question="Test question",
        expected_pages=(20,),
        retrieved_pages=(20, 50),
        retrieval_hit_rate=1.0,
        retrieval_recall=1.0,
        retrieval_precision=0.5,
        retrieval_reciprocal_rank=1.0,
        generation=generation,
        error=error,
    )


def make_summary(
    results: tuple[BenchmarkQuestionResult, ...],
) -> BenchmarkSummary:
    return BenchmarkSummary(
        results=results,
        retrieval_hit_rate=1.0,
        retrieval_recall=0.9,
        retrieval_precision=0.5,
        retrieval_mrr=0.8,
        answer_rate=0.9,
        citation_rate=0.8,
        relevant_citation_rate=0.7,
        abstention_rate=0.1,
        valid_citation_rate=0.8,
        unsupported_citation_rate=0.0,
    )


def test_format_pages_returns_list_representation():
    assert _format_pages((20, 21, 50)) == "[20, 21, 50]"


def test_print_question_result_reports_success(capsys):
    result = make_question_result(
        generation=make_generation_result(),
    )

    _print_question_result(
        index=1,
        result=result,
        limit=5,
    )

    output = capsys.readouterr().out

    assert "Q01 [PASS]" in output
    assert "Test question" in output
    assert "Expected pages: [20]" in output
    assert "Retrieved pages: [20, 50]" in output
    assert "Hit@5: 1.00" in output
    assert "Recall@5: 1.00" in output
    assert "P@5: 0.50" in output
    assert "RR: 1.00" in output
    assert "Answer: YES" in output
    assert "Abstention: NO" in output
    assert "Citations: YES" in output
    assert "Cited pages: [20]" in output
    assert "Relevant cited pages: [20]" in output


def test_print_question_result_reports_missing_citations_as_failure(
    capsys,
):
    result = make_question_result(
        generation=make_generation_result(
            has_citations=False,
            citation_pages=(),
            cited_relevant_pages=(),
        ),
    )

    _print_question_result(
        index=8,
        result=result,
        limit=5,
    )

    output = capsys.readouterr().out

    assert "Q08 [FAIL]" in output
    assert "Answer: YES" in output
    assert "Abstention: NO" in output
    assert "Citations: NO" in output
    assert "Cited pages: []" in output


def test_print_question_result_reports_generation_error(capsys):
    result = make_question_result(
        generation=None,
        error=(
            "ValueError: Invalid citation IDs "
            "generated by the model: [9]"
        ),
    )

    _print_question_result(
        index=3,
        result=result,
        limit=5,
    )

    output = capsys.readouterr().out

    assert "Q03 [ERROR]" in output
    assert "Generation → ERROR" in output
    assert "ValueError: Invalid citation IDs" in output


def test_print_question_result_reports_unsupported_citations(capsys):
    result = make_question_result(
        generation=make_generation_result(
            citation_pages=(20, 99),
            cited_relevant_pages=(20,),
            unsupported_citation_pages=(99,),
        ),
    )

    _print_question_result(
        index=1,
        result=result,
        limit=5,
    )

    output = capsys.readouterr().out

    assert "Unsupported cited pages: [99]" in output


def test_print_summary_reports_metrics(capsys):
    result = make_question_result(
        generation=make_generation_result(),
    )

    summary = make_summary(
        results=(result,),
    )

    _print_summary(
        summary=summary,
        limit=5,
    )

    output = capsys.readouterr().out

    assert "RETRIEVAL" in output
    assert "Hit Rate@5: 100.00%" in output
    assert "Recall@5:   90.00%" in output
    assert "Precision@5: 50.00%" in output
    assert "MRR@5:       80.00%" in output

    assert "GENERATION" in output
    assert "Answer Rate:              90.00%" in output
    assert "Citation Rate:            80.00%" in output
    assert "Relevant Citation Rate:   70.00%" in output
    assert "Abstention Rate:          10.00%" in output
    assert "Valid Citation Rate:      80.00%" in output
    assert "Unsupported Citation Rate: 0.00%" in output

    assert "Questions: 1" in output
    assert "Passed: 1" in output
    assert "Failed: 0" in output
    assert "Generation errors: 0" in output


def test_evaluate_runs_dataset_and_returns_summary():
    result = make_question_result(
        generation=make_generation_result(),
    )

    summary = make_summary(
        results=(result,),
    )

    with patch(
        "app.evaluation.evaluator.evaluate_dataset",
        return_value=summary,
    ) as mocked_evaluate_dataset:
        returned = evaluate(limit=5)

    mocked_evaluate_dataset.assert_called_once()

    call_kwargs = mocked_evaluate_dataset.call_args.kwargs

    assert call_kwargs["limit"] == 5
    assert returned is summary