def test_evaluate_dataset_aggregates_results():
    dataset = [
        EvaluationQuestion(
            question="Question one",
            relevant_pages=(20,),
        ),
        EvaluationQuestion(
            question="Question two",
            relevant_pages=(30,),
        ),
    ]

    first_results = [
        make_search_result(20),
        make_search_result(50),
    ]

    second_results = [
        make_search_result(99),
        make_search_result(30),
    ]

    first_answer = make_answer(
        citations=(
            make_citation(1, 20),
        ),
    )

    second_answer = make_answer()

    with patch(
        "app.evaluation.benchmark.search",
        side_effect=[
            first_results,
            second_results,
        ],
    ), patch(
        "app.evaluation.benchmark.answer_from_results",
        side_effect=[
            first_answer,
            second_answer,
        ],
    ):
        summary = evaluate_dataset(
            dataset=dataset,
            limit=2,
        )

    assert len(summary.results) == 2

    assert summary.retrieval_hit_rate == 1.0
    assert summary.retrieval_recall == 1.0
    assert summary.retrieval_precision == 0.5

    assert summary.retrieval_mrr == 0.75

    assert summary.answer_rate == 1.0
    assert summary.citation_rate == 0.5
    assert summary.abstention_rate == 0.0
    assert summary.valid_citation_rate == 1.0
    assert summary.unsupported_citation_rate == 0.0


def test_evaluate_dataset_counts_generation_errors_as_non_answers():
    dataset = [
        EvaluationQuestion(
            question="Successful question",
            relevant_pages=(20,),
        ),
        EvaluationQuestion(
            question="Failed question",
            relevant_pages=(30,),
        ),
    ]

    results = [
        make_search_result(20),
    ]

    answer = make_answer(
        citations=(
            make_citation(1, 20),
        ),
    )

    with patch(
        "app.evaluation.benchmark.search",
        side_effect=[
            results,
            results,
        ],
    ), patch(
        "app.evaluation.benchmark.answer_from_results",
        side_effect=[
            answer,
            ValueError(
                "Invalid citation IDs generated by the model: [9]"
            ),
        ],
    ):
        summary = evaluate_dataset(
            dataset=dataset,
            limit=1,
        )

    assert len(summary.results) == 2

    assert summary.results[0].generation is not None
    assert summary.results[0].error is None

    assert summary.results[1].generation is None
    assert summary.results[1].error is not None

    assert summary.answer_rate == 0.5
    assert summary.citation_rate == 0.5
    assert summary.valid_citation_rate == 0.5


