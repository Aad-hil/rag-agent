from unittest.mock import patch

from app.evaluation.benchmark import (
    evaluate_dataset,
    evaluate_question,
)
from app.evaluation.dataset import EvaluationQuestion
from app.generation.answer import Answer, AnswerCitation
from app.retrieval.search import SearchResult


def make_search_result(
    page_number: int,
    chunk_index: int = 0,
) -> SearchResult:
    return SearchResult(
        text=f"Content from page {page_number}.",
        score=0.9,
        source="test.pdf",
        page_number=page_number,
        chunk_index=chunk_index,
    )


def make_answer(
    citations: tuple[AnswerCitation, ...] = (),
) -> Answer:
    return Answer(
        text="This is a test answer.",
        citations=citations,
    )


def make_citation(
    citation_id: int,
    page_number: int,
) -> AnswerCitation:
    return AnswerCitation(
        citation_id=citation_id,
        source="test.pdf",
        page_number=page_number,
        chunk_index=0,
    )


def test_evaluate_question_uses_retrieval_results_for_generation():
    item = EvaluationQuestion(
        question="Test question",
        relevant_pages=(20, 21),
    )

    results = [
        make_search_result(20),
        make_search_result(21),
        make_search_result(50),
    ]

    answer = make_answer(
        citations=(
            make_citation(1, 20),
            make_citation(2, 21),
        ),
    )

    with patch(
        "app.evaluation.benchmark.search",
        return_value=results,
    ) as mocked_search, patch(
        "app.evaluation.benchmark.answer_from_results",
        return_value=answer,
    ) as mocked_answer_from_results:
        result = evaluate_question(
            item=item,
            limit=5,
        )

    mocked_search.assert_called_once_with(
        "Test question",
        limit=5,
    )

    mocked_answer_from_results.assert_called_once_with(
        question="Test question",
        results=results,
    )

    assert result.error is None

    assert result.retrieved_pages == (
        20,
        21,
        50,
    )

    assert result.retrieval_hit_rate == 1.0
    assert result.retrieval_recall == 1.0
    assert result.retrieval_precision == 2 / 3
    assert result.retrieval_reciprocal_rank == 1.0

    assert result.generation is not None
    assert result.generation.has_answer is True
    assert result.generation.has_citations is True

    assert result.generation.citation_pages == (
        20,
        21,
    )


def test_evaluate_question_preserves_retrieval_metrics_when_generation_fails():
    item = EvaluationQuestion(
        question="Test question",
        relevant_pages=(20,),
    )

    results = [
        make_search_result(20),
        make_search_result(50),
    ]

    with patch(
        "app.evaluation.benchmark.search",
        return_value=results,
    ), patch(
        "app.evaluation.benchmark.answer_from_results",
        side_effect=ValueError(
            "Invalid citation IDs generated by the model: [9]"
        ),
    ):
        result = evaluate_question(
            item=item,
            limit=5,
        )

    assert result.generation is None
    assert result.error is not None
    assert "ValueError" in result.error
    assert "Invalid citation IDs" in result.error

    assert result.retrieved_pages == (
        20,
        50,
    )

    assert result.retrieval_hit_rate == 1.0
    assert result.retrieval_recall == 1.0
    assert result.retrieval_precision == 0.5
    assert result.retrieval_reciprocal_rank == 1.0


